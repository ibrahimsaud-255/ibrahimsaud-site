create table if not exists public.radar_scripts (
  id          text primary key,
  title       text,
  body        text,
  tags        jsonb default '[]'::jsonb,
  stage       text default 'فكرة',
  client_id   text,
  client_name text,
  source      text,   -- 'idea' | 'product' | 'manual'
  source_ref  text,   -- معرف الفكرة أو رابط المنتج
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);
create index if not exists radar_scripts_stage_idx  on public.radar_scripts(stage);
create index if not exists radar_scripts_client_idx on public.radar_scripts(client_name);

alter table public.radar_scripts enable row level security;
-- نفس نموذج content_ideas: أداة داخلية بلا تسجيل دخول
drop policy if exists rs_all on public.radar_scripts;
